//! Generated once from the schema by the L1b authoring pass, then maintained by hand: maps every
//! `$defs` name to its Rust type so the contract test can round-trip any value through it.
#![allow(dead_code)]
use loomward_protocol::*;
use serde::{de::DeserializeOwned, Serialize};
use serde_json::Value;

fn rt<T: DeserializeOwned + Serialize>(v: &Value) -> Result<Value, String> {
    let t: T = decode_exact(v.clone()).map_err(|e| e.message.to_string())?;
    serde_json::to_value(&t).map_err(|e| e.to_string())
}

